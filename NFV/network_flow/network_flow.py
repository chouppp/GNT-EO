import os
import random
import copy
from typing import List, Dict, Tuple, Optional
import yaml

class VNRFlowSimulator:
    """Simulate physical-link traffic from VNE mappings and write link_single_table.current_Flow."""

    def __init__(
        self,
        vne_links: List[Dict],
        alpha_range: Tuple[float, float] = (0.8, 1.2),
        link_noise: float = 0,
        seed: Optional[int] = None,
        vnr_id=None
    ):
        self.base_links = copy.deepcopy(vne_links)
        self.alpha_range = alpha_range
        self.link_noise = link_noise
        if seed is not None:
            random.seed(seed)
        self.time = 0
        self.flow_history = []
        self.vnr_id = vnr_id

    def step_generate_flow(self):
        self.time += 1
        alpha = random.uniform(*self.alpha_range)

        phy_link_load = {}

        for vlink in self.base_links:
            base_bw = float(vlink["bw"])
            curr_bw = base_bw * alpha

            for u, v in vlink["linkpath"]:
                edge = (int(u), int(v))
                phy_link_load[edge] = phy_link_load.get(edge, 0.0) + curr_bw

        return phy_link_load

    # Record the traffic generated by each VNR at each stage.
    def append_flow_record_to_yaml(record, yaml_path="vnr_flow_history.yaml"):
        """Append traffic-generation records for all time steps."""
        if os.path.exists(yaml_path):
            with open(yaml_path, "r", encoding="utf-8") as f:
                data = yaml.safe_load(f) or {}
        else:
            data = {
                "records": []
            }

        data.setdefault("records", [])
        data["records"].append(record)

        with open(yaml_path, "w", encoding="utf-8") as f:
            yaml.safe_dump(
                data,
                f,
                sort_keys=False,
                allow_unicode=True
            )

    def write_flow_to_db(
        self,
        conn,
        phy_link_load: Dict[Tuple[int, int], float],
        commit: bool = True,
        update_reverse_if_missing: bool = False,
    ) -> int:
        """Write phy_link_load to link_single_table.current_Flow.
        
                Parameters
                ----------
                conn: initialized database connection returned by pymysql.connect.
                phy_link_load: {(u,v): flow}.
                commit: whether to commit the updates.
                update_reverse_if_missing: try (v,u) if updating (u,v) affects no row.
        
                Returns
                -------
                affected_rows: total rows affected by this UPDATE operation."""
        sql = """
        UPDATE link_single_table
        SET current_flow = %s
        WHERE source_node = %s AND destination_node = %s
        """

        affected_rows = 0
        with conn.cursor() as cursor:
            for (u, v), flow in phy_link_load.items():
                cursor.execute(sql, (float(flow), int(u), int(v)))
                if cursor.rowcount == 0 and update_reverse_if_missing:
                    cursor.execute(sql, (float(flow), int(v), int(u)))
                affected_rows += cursor.rowcount

        if commit:
            conn.commit()

        return affected_rows

    def step_and_write(
            self,
            conn,
            commit=True,
            update_reverse_if_missing=False,
            current_time=None,
            yaml_path="vnr_flow_history.yaml",
            save_yaml=True
    ):
        """One time step: generate traffic, write to the database, and save traffic history."""
        flow = self.step_generate_flow()

        reset_sql = """
        UPDATE link_single_table
        SET current_flow = 0
        """

        update_sql = """
        UPDATE link_single_table
        SET current_flow = %s
        WHERE source_node = %s AND destination_node = %s
        """

        with conn.cursor() as cursor:
            cursor.execute(reset_sql)

            for (u, v), bw in flow.items():
                cursor.execute(update_sql, (float(bw), int(u), int(v)))

                if cursor.rowcount == 0 and update_reverse_if_missing:
                    cursor.execute(update_sql, (float(bw), int(v), int(u)))

        if commit:
            conn.commit()

        if save_yaml:
            record = {
                "time": float(current_time) if current_time is not None else self.time,
                "step": int(self.time),
                "active_vnr_num": len(self.vnr_simulators),
                "vnr_flows": self.last_vnr_flow_records,
                "global_link_flow": [
                    {
                        "source": int(u),
                        "target": int(v),
                        "flow": float(bw)
                    }
                    for (u, v), bw in flow.items()
                ]
            }

            self.append_flow_record_to_yaml(record, yaml_path)

        return flow